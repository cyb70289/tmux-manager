import Foundation

public final class ConfigStore {
    public let paths: Paths
    private let queue = DispatchQueue(label: "com.cyb.tmuxmanager.config")

    public init(paths: Paths = .default) {
        self.paths = paths
    }

    public enum LoadResult {
        case loaded(Config, notes: [String])
        case empty(notes: [String])
        case failed(String)
    }

    /// Reads the config, tolerating a missing file. Never throws.
    public func load() -> LoadResult {
        guard FileManager.default.fileExists(atPath: paths.configURL.path) else {
            return .empty(notes: [])
        }
        do {
            let data = try Data(contentsOf: paths.configURL)
            let decoder = JSONDecoder()
            let config: Config
            do {
                config = try decoder.decode(Config.self, from: data)
            } catch {
                return .failed("config.json is not valid: \(error.localizedDescription)")
            }
            var notes: [String] = []
            var seen = Set<String>()
            for entry in config.entries {
                if !seen.insert(entry.id).inserted {
                    notes.append("Duplicate entry id for \(entry.address).")
                }
                if let problem = EntryValidator.message(for: EntryValidator.problems(for: entry, all: config.entries)) {
                    notes.append("\(entry.displayName): \(problem)")
                }
            }
            return .loaded(config, notes: notes)
        } catch {
            return .failed("Cannot read config.json: \(error.localizedDescription)")
        }
    }

    public func save(_ config: Config) throws {
        try paths.prepareDirectories()
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        var data = try encoder.encode(config)
        data.append(0x0A)
        let tmp = paths.supportDir.appendingPathComponent(".config.json.tmp")
        try data.write(to: tmp, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: tmp.path)
        if FileManager.default.fileExists(atPath: paths.configURL.path) {
            _ = try FileManager.default.replaceItemAt(paths.configURL, withItemAt: tmp)
        } else {
            try FileManager.default.moveItem(at: tmp, to: paths.configURL)
        }
        try writeEnvFiles(for: config)
    }

    /// Per-entry shell file the wrapper sources on every (re)connect.
    public func writeEnvFiles(for config: Config) throws {
        try paths.prepareDirectories()
        var wanted = Set<String>()
        for entry in config.entries {
            let url = paths.envURL(entryID: entry.id)
            wanted.insert(url.lastPathComponent)
            try envContents(for: entry).write(to: url, atomically: true, encoding: .utf8)
        }
        let existing = (try? FileManager.default.contentsOfDirectory(atPath: paths.envDir.path)) ?? []
        for name in existing where !wanted.contains(name) {
            try? FileManager.default.removeItem(at: paths.envDir.appendingPathComponent(name))
        }
    }

    public func envContents(for entry: Entry) -> String {
        var lines: [String] = []
        lines.append("# Generated by TmuxManager. Do not edit.")
        lines.append("ENTRY_ID=\(Quote.shell(entry.id))")
        lines.append("DISPLAY_NAME=\(Quote.shell(entry.displayName))")
        lines.append("HOST=\(Quote.shell(entry.host))")
        lines.append("SESSION=\(Quote.shell(entry.session))")
        lines.append("TMUX_PATH=\(Quote.shell(entry.effectiveTmuxPath))")
        let options = entry.sshOptions.map(Quote.shell).joined(separator: " ")
        lines.append("EXTRA_SSH_OPTS=( \(options) )")
        lines.append("DETACH_OTHER_CLIENTS=\(entry.detachOtherClients ? 1 : 0)")
        return lines.joined(separator: "\n") + "\n"
    }

    /// Removes env + state files for entries that no longer exist.
    public func cleanupOrphans(config: Config) {
        let ids = Set(config.entries.map(\.id))
        for name in (try? FileManager.default.contentsOfDirectory(atPath: paths.envDir.path)) ?? [] {
            let id = (name as NSString).deletingPathExtension
            if !ids.contains(id) {
                try? FileManager.default.removeItem(at: paths.envDir.appendingPathComponent(name))
            }
        }
    }
}

/// Watches the support directory so that hand edits of config.json are picked up.
public final class ConfigWatcher {
    private let paths: Paths
    private let queue = DispatchQueue(label: "com.cyb.tmuxmanager.configwatch")
    private var source: DispatchSourceFileSystemObject?
    private var pending: DispatchWorkItem?
    public var onChange: (() -> Void)?

    public init(paths: Paths = .default) {
        self.paths = paths
    }

    public func start() {
        stop()
        let descriptor = open(paths.supportDir.path, O_EVTONLY)
        guard descriptor >= 0 else { return }
        let src = DispatchSource.makeFileSystemObjectSource(
            fileDescriptor: descriptor, eventMask: [.write, .rename, .delete], queue: queue)
        src.setEventHandler { [weak self] in
            guard let self else { return }
            self.pending?.cancel()
            let work = DispatchWorkItem { [weak self] in self?.onChange?() }
            self.pending = work
            self.queue.asyncAfter(deadline: .now() + 0.25, execute: work)
        }
        src.setCancelHandler { close(descriptor) }
        src.resume()
        source = src
    }

    public func stop() {
        source?.cancel()
        source = nil
        pending?.cancel()
        pending = nil
    }

    deinit { stop() }
}
