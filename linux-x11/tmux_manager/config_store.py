from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Tuple

from .config import Config, Entry, shell_quote, validate_entry, validation_message
from .paths import Paths


@dataclass
class LoadResult:
    status: str  # "loaded" | "empty" | "failed"
    config: Optional[Config] = None
    notes: List[str] | None = None
    error: Optional[str] = None


class ConfigStore:
    def __init__(self, paths: Paths) -> None:
        self.paths = paths

    def load(self) -> LoadResult:
        if not self.paths.config_path.exists():
            return LoadResult(status="empty", config=Config(), notes=[])
        try:
            raw = self.paths.config_path.read_text(encoding="utf-8")
        except OSError as exc:
            return LoadResult(status="failed", error=f"Cannot read config.json: {exc}")
        try:
            data = json.loads(raw)
            config = Config.from_dict(data)
        except Exception as exc:
            return LoadResult(status="failed", error=f"config.json is not valid: {exc}")

        notes: List[str] = []
        seen: set[str] = set()
        for entry in config.entries:
            if entry.id in seen:
                notes.append(f"Duplicate entry id for {entry.address}.")
            seen.add(entry.id)
            problem = validation_message(validate_entry(entry, config.entries))
            if problem:
                notes.append(f"{entry.display_name}: {problem}")
        return LoadResult(status="loaded", config=config, notes=notes)

    def save(self, config: Config) -> None:
        self.paths.prepare_directories()
        payload = json.dumps(config.to_dict(), indent=2, sort_keys=True) + "\n"
        tmp = self.paths.support_dir / f".config.json.{os.getpid()}.tmp"
        tmp.write_text(payload, encoding="utf-8")
        os.chmod(tmp, 0o600)
        os.replace(tmp, self.paths.config_path)
        self.write_env_files(config)

    def write_env_files(self, config: Config) -> None:
        self.paths.prepare_directories()
        wanted: set[str] = set()
        for entry in config.entries:
            path = self.paths.env_path(entry.id)
            wanted.add(path.name)
            tmp = self.paths.env_dir / f".{entry.id}.{os.getpid()}.tmp"
            tmp.write_text(self.env_contents(entry), encoding="utf-8")
            os.chmod(tmp, 0o600)
            os.replace(tmp, path)
        for item in self.paths.env_dir.iterdir():
            if item.is_file() and not item.name.startswith(".") and item.name not in wanted:
                try:
                    item.unlink()
                except OSError:
                    pass

    @staticmethod
    def env_contents(entry: Entry) -> str:
        options = " ".join(shell_quote(opt) for opt in entry.ssh_options)
        lines = [
            "# Generated by TmuxManager. Do not edit.",
            f"ENTRY_ID={shell_quote(entry.id)}",
            f"DISPLAY_NAME={shell_quote(entry.display_name)}",
            f"HOST={shell_quote(entry.host)}",
            f"SESSION={shell_quote(entry.session)}",
            f"TMUX_PATH={shell_quote(entry.effective_tmux_path)}",
            f"EXTRA_SSH_OPTS=( {options} )",
            f"DETACH_OTHER_CLIENTS={1 if entry.detach_other_clients else 0}",
        ]
        return "\n".join(lines) + "\n"

    def cleanup_orphans(self, config: Config) -> None:
        if not self.paths.env_dir.exists():
            return
        ids = {e.id for e in config.entries}
        for item in self.paths.env_dir.iterdir():
            if item.is_file() and item.suffix == ".sh":
                if item.stem not in ids:
                    try:
                        item.unlink()
                    except OSError:
                        pass

    def stat_stamp(self) -> Optional[Tuple[int, int, int]]:
        try:
            st = self.paths.config_path.stat()
            return (st.st_mtime_ns, st.st_size, st.st_ino)
        except OSError:
            return None
